import { expect, test } from '@playwright/test';

test('bonus offers share one account, keep obligations independent, and persist through edits, filters and refresh', async({page,request})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>localStorage.setItem('minty_lock',JSON.stringify({state:'off'})));
  const suffix=Date.now().toString(),name=`Bonus account ${suffix}`,ownerName=`Bonus owner ${suffix}`;
  const beforeAccounts=await(await request.get('/accounts?view=all')).json();
  const owner=await(await request.post('/people',{data:{label:ownerName}})).json();
  const account=await(await request.post('/accounts',{data:{owner:owner.id,name,detailed_type:'checking',currency:'USD',balance_cents:50000}})).json();
  await page.goto('/account-overview');
  await page.locator('#people').getByRole('button',{name:ownerName,exact:true}).click();
  const card=page.locator('.account-card').filter({has:page.getByRole('heading',{name,exact:true})});
  await expect(card).toContainText('Opening bonus: Unknown');
  await card.getByRole('button',{name:'Opening & bonus details',exact:true}).click();
  const editor=page.locator('#bonusEditor'),accountForm=page.locator('#bonusAccountForm'),offerForm=page.locator('#bonusOfferForm');
  await expect(editor).toBeVisible();
  await expect(page.locator('#bonusOfferSection')).toBeHidden();
  await expect(accountForm.locator('[name=opened_date]')).toHaveValue('');
  await accountForm.locator('[name=opened_date]').fill('2025-01-31');
  await accountForm.locator('[name=bonus_answer]').selectOption('yes');
  await accountForm.locator('[name=monthly_fee]').fill('12');
  await accountForm.locator('[name=fee_waiver]').fill('Maintain a qualifying balance or direct deposit.');
  await accountForm.getByRole('button',{name:'Save account details',exact:true}).click();
  await expect(page.locator('#bonusEditorStatus')).toContainText('Account details saved');
  await expect(page.locator('#bonusOriginalWrap')).toBeHidden();
  await expect(page.locator('#bonusTriggerWrap')).toBeHidden();
  await expect(page.locator('#bonusOverrideWrap')).toBeHidden();
  await offerForm.locator('[name=offer_name]').fill(`First offer ${suffix}`);
  await offerForm.locator('[name=offer_url]').fill('https://example.com/offer');
  await offerForm.locator('[name=expected_amount]').fill('200');
  await offerForm.locator('[name=expected_payout_date]').fill('2025-04-01');
  await offerForm.locator('[name=terms_notes]').fill('Check all conditions before closing.');
  await offerForm.locator('[name=save_original]').check();
  const original='Original terms text\nKeep open six calendar months after the latest bonus installment.\n';
  await offerForm.locator('[name=original_terms]').fill(original);
  await offerForm.locator('[name=minimum_open_period]').fill('Six months after the latest bonus installment.');
  await offerForm.locator('[name=rule_trigger]').selectOption('last_payment');
  await offerForm.locator('[name=rule_value]').fill('6');
  await offerForm.locator('[name=rule_unit]').selectOption('months');
  await offerForm.locator('[name=rule_text]').fill('Offer terms explicitly require six months after the latest recorded bonus installment.');
  await offerForm.getByRole('button',{name:'Save offer',exact:true}).click();
  await expect(page.locator('#bonusEditorStatus')).toContainText('Offer saved');
  await expect(page.locator('#bonusCalculation')).toContainText('Closure terms unknown');
  const newReq=page.locator('#newBonusRequirement');
  await newReq.locator('[name=description]').fill('Maintain the qualifying balance through March 1');
  await newReq.locator('[name=deadline]').fill('2025-03-01');
  await newReq.getByRole('button',{name:'Add requirement',exact:true}).click();
  await expect(page.locator('#bonusRequirements')).toContainText('Overdue requirement');
  await page.getByRole('button',{name:'Close',exact:true}).click();
  await page.getByRole('button',{name:'Bonus tracker',exact:true}).click();
  await expect(page.locator('#bonusList .bonus-row')).toHaveCount(1);
  await expect(page.locator('#bonusList')).toContainText('Overdue expected payout');
  await expect(page.locator('#bonusList')).toContainText('Overdue requirements: 1');
  for(const filter of ['requirements','payment']){
    await page.locator('#bonusFilter').selectOption(filter);
    await expect(page.locator('#bonusList .bonus-row')).toHaveCount(1);
  }
  await page.locator('#bonusList').getByRole('button',{name:'View / edit offer',exact:true}).click();
  const payment=page.locator('#newBonusPayment');
  await payment.locator('[name=amount]').fill('75');await payment.locator('[name=received_date]').fill('2025-02-10');
  await payment.getByRole('button',{name:'Record payment',exact:true}).click();
  await expect(page.locator('#bonusPaymentSummary')).toContainText('Partially received');
  await expect(page.locator('#bonusCalculation')).toContainText('2025-08-10');
  await expect(page.locator('#bonusRequirements')).toContainText('Overdue requirement');
  const req=page.locator('form[data-requirement]');
  await req.locator('[name=done]').check();await req.locator('[name=completed_date]').fill('2025-03-02');
  await req.getByRole('button',{name:'Save requirement',exact:true}).click();
  await expect(page.locator('#bonusRequirements')).toContainText('Completed after its deadline');
  await expect(page.locator('#bonusPaymentSummary')).toContainText('Partially received');
  await payment.locator('[name=amount]').fill('125');await payment.locator('[name=received_date]').fill('2025-02-20');
  await payment.getByRole('button',{name:'Record payment',exact:true}).click();
  await expect(page.locator('#bonusPaymentSummary')).toContainText('Expected amount received');
  await expect(page.locator('#bonusCalculation')).toContainText('2025-08-20');
  await expect(page.locator('#bonusCalculation')).toContainText('Closure date reached');
  await page.getByRole('button',{name:'Close',exact:true}).click();
  await page.locator('#bonusFilter').selectOption('reached');
  await expect(page.locator('#bonusList .bonus-row')).toHaveCount(1);
  await expect(page.locator('#bonusList')).not.toContainText('Overdue expected payout');
  await page.locator('#bonusList').getByRole('button',{name:'View / edit offer',exact:true}).click();
  await offerForm.locator('[name=use_override]').check();
  await offerForm.locator('[name=closure_override_date]').fill('2030-01-01');
  await offerForm.locator('[name=closure_override_reason]').fill('Manually reviewed later holding obligation.');
  await offerForm.getByRole('button',{name:'Save offer',exact:true}).click();
  await expect(page.locator('#bonusCalculation')).toContainText('Keep open until 2030-01-01');
  await expect(page.locator('#bonusCalculation')).toContainText('Calculated date retained for comparison: 2025-08-20');
  await page.getByRole('button',{name:'Close',exact:true}).click();
  await page.locator('#bonusFilter').selectOption('holding');
  await expect(page.locator('#bonusList .bonus-row')).toHaveCount(1);
  await page.locator('#bonusList').getByRole('button',{name:'View / edit offer',exact:true}).click();
  await page.getByRole('button',{name:'New offer',exact:true}).click();
  await offerForm.locator('[name=offer_name]').fill(`Unknown terms ${suffix}`);
  await offerForm.getByRole('button',{name:'Save offer',exact:true}).click();
  await expect(page.locator('#bonusEditorStatus')).toContainText('Offer saved');
  await expect(page.locator('#bonusCalculation')).toContainText('Closure terms unknown');
  await page.getByRole('button',{name:'Close',exact:true}).click();
  await page.locator('#bonusFilter').selectOption('all');
  await expect(page.locator('#bonusList .bonus-row')).toHaveCount(2);
  await expect(page.locator('#bonusList').getByText('All offers on this account:',{exact:false}).first()).toContainText('Closure terms unknown');
  await page.locator('#bonusFilter').selectOption('reached');
  await expect(page.locator('#bonusList .bonus-row')).toHaveCount(0);
  await page.locator('#bonusFilter').selectOption('holding');
  await expect(page.locator('#bonusList .bonus-row')).toHaveCount(2);
  await page.locator('#bonusFilter').selectOption('all');
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.reload();
  await page.locator('#people').getByRole('button',{name:ownerName,exact:true}).click();
  await expect(page.locator('#bonusList .bonus-row')).toHaveCount(2);
  const first=page.locator('.bonus-row').filter({hasText:`First offer ${suffix}`});
  await first.getByRole('button',{name:'View / edit offer',exact:true}).click();
  await expect(offerForm.locator('[name=original_terms]')).toHaveValue(original);
  await expect(page.locator('#bonusRequirements [name=done]')).toBeChecked();
  await expect(page.locator('#bonusPayments form')).toHaveCount(2);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await accountForm.locator('[name=account_status]').selectOption('closed');
  await accountForm.locator('[name=closed_date]').fill('2025-12-01');
  await accountForm.getByRole('button',{name:'Save account details',exact:true}).click();
  await expect(page.locator('#bonusEditorStatus')).toContainText('Account details saved');
  await page.getByRole('button',{name:'Close',exact:true}).click();
  await page.locator('#bonusFilter').selectOption('closed');
  await expect(page.locator('#bonusList .bonus-row')).toHaveCount(2);
  await expect(page.locator('#bonusList')).not.toContainText('safe to close');
  await page.getByRole('button',{name:'Inventory',exact:true}).click();
  await expect(card).toContainText('Closed');
  const saved=await(await request.get('/accounts?view=all')).json();
  expect(saved).toHaveLength(beforeAccounts.length+1);expect(saved.find((a:any)=>a.id===account.id).balance_current).toBe(500);
  expect((await(await request.get('/items')).json())).toEqual([]);
  // A received bonus with an unknown date must not invent the latest-payment holding trigger.
  await card.getByRole('button',{name:'Opening & bonus details',exact:true}).click();
  await offerForm.locator('[name=use_override]').uncheck();
  await offerForm.getByRole('button',{name:'Save offer',exact:true}).click();
  await expect(page.locator('#bonusEditorStatus')).toContainText('Offer saved');
  await expect(page.locator('#bonusCalculation')).toContainText('2025-08-20');
  await payment.locator('[name=amount]').fill('1');
  await payment.locator('[name=received_date]').fill('');
  await payment.getByRole('button',{name:'Record payment',exact:true}).click();
  await expect(page.locator('#bonusCalculation')).toContainText('Closure terms unknown');
  await expect(page.locator('#bonusCalculation')).toContainText('payment dates are unknown');
  await expect(page.locator('#bonusPaymentSummary')).toContainText('Expected amount received');
  await page.locator('#bonusOfferSelect').selectOption({index:2});
  await payment.locator('[name=received_date]').fill('2025-02-21');
  await payment.getByRole('button',{name:'Record payment',exact:true}).click();
  await expect(page.locator('#bonusPaymentSummary')).toContainText('Payment amounts incomplete');
  await expect(page.locator('#bonusPaymentSummary')).toContainText('Unknown received');
  expect(errors).toEqual([]);
});
